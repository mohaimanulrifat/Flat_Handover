export const DEFAULT_OWNER_SHARE_PCT = 50;

/**
 * Share of the total floor area that becomes flats to sell or keep, in
 * percent. The rest is stairs, lift, lobby, walls and other common space.
 */
export const DEFAULT_SALEABLE_PCT = 70;
